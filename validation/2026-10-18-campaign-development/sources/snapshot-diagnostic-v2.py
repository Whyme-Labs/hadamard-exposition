"""Archive unchanged diagnostic evidence, explicitly omitting public input bodies."""
import argparse
import gzip
import hashlib
import json
from pathlib import Path
import shutil
import stat
import tarfile

ROOT = Path(__file__).resolve().parents[3]


def digest(path):
    value = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            value.update(block)
    return value.hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--kind", choices=("inputs", "advice", "trace"), required=True)
    args = parser.parse_args()
    source, output = args.input.resolve(strict=True), args.output.absolute()
    if (not source.is_relative_to(ROOT / "build") or not output.is_relative_to(ROOT / "validation")
            or source.is_relative_to(output) or output.is_relative_to(source)
            or output.parent.resolve() != output.parent):
        raise ValueError("Use a fresh concrete validation directory outside the original build inputs")
    files = []
    for path in source.rglob("*"):
        if path.is_symlink() or not (path.is_dir() or stat.S_ISREG(path.lstat().st_mode)):
            raise ValueError("Special files or links cannot be archived as original regular evidence")
        if path.is_file():
            files.append(path)
    output.mkdir(exist_ok=False)
    record = {"schema_version": "hadamard-diagnostic-archive.v2", "kind": args.kind,
              "original_directory": source.relative_to(ROOT).as_posix(), "members": [], "omissions": [],
              "archival_model_calls": 0, "snapshot_source_sha256": digest(Path(__file__)),
              "separate_copies": {}, "note": "Receipts and observations are unchanged byte copies. Omitted public inputs have fresh observed identities; no model result is regenerated by archiving."}
    archive_path = output / "raw-evidence.tar.gz"
    with archive_path.open("xb") as raw, gzip.GzipFile(fileobj=raw, mode="wb", filename="", mtime=0) as zipped:
        with tarfile.open(fileobj=zipped, mode="w", format=tarfile.PAX_FORMAT) as archive:
            for path in sorted(files):
                name = path.relative_to(source).as_posix()
                entry = {"path": name, "bytes": path.stat().st_size, "sha256": digest(path)}
                if args.kind == "inputs" and name.startswith(("artifacts/model/", "new-acquisition/artifacts/model/", "new-acquisition/artifacts/dataset/")):
                    record["omissions"].append({**entry, "reason": "Reacquired public input body; original and fresh acquisition receipts and exact byte identities are retained."})
                    continue
                if entry["bytes"] > 128 * 1024**2:
                    raise ValueError("Unexpected oversized evidence needs explicit retention review")
                info = tarfile.TarInfo(name)
                info.size, info.mode, info.mtime = entry["bytes"], 0o644, 0
                with path.open("rb") as stream:
                    archive.addfile(info, stream)
                if path.stat().st_size != entry["bytes"] or digest(path) != entry["sha256"]:
                    raise ValueError("Original evidence changed during archival")
                record["members"].append(entry)
    copies = {"inputs": {"reconstruction.json": "reconstruction.json", "acquisition.json": "new-acquisition/artifacts/acquisition.json", "acquisition-host.json": "acquisition-host.json"},
              "advice": {"advice.json": "advice.json"},
              "trace": {"trace-run.json": "trace-run.json", "preflight.json": "preflight.json", "worker-result.json": "worker/worker-result.json"}}[args.kind]
    for name, relative in copies.items():
        original = source / relative
        if original.is_file():
            with original.open("rb") as src, (output / name).open("xb") as dest:
                shutil.copyfileobj(src, dest, 1024 * 1024)
            record["separate_copies"][name] = {"original_path": relative, "bytes": original.stat().st_size, "sha256": digest(original)}
            if digest(output / name) != record["separate_copies"][name]["sha256"]:
                raise ValueError("Standalone copy differs from the original receipt")
    with tarfile.open(archive_path, "r:gz") as archive:
        members = archive.getmembers()
        if len(members) != len(record["members"]):
            raise ValueError("Archive member count differs")
        for item in record["members"]:
            data = archive.extractfile(item["path"]).read()
            if len(data) != item["bytes"] or hashlib.sha256(data).hexdigest() != item["sha256"]:
                raise ValueError("Archive readback differs from its inventory")
    record["archive"] = {"path": archive_path.name, "bytes": archive_path.stat().st_size, "sha256": digest(archive_path),
                         "member_count": len(record["members"]), "uncompressed_member_bytes": sum(x["bytes"] for x in record["members"])}
    with (output / "inventory.json").open("x") as stream:
        json.dump(record, stream, indent=2, sort_keys=True, allow_nan=False)
        stream.write("\n")
    print(json.dumps(record["archive"]))


if __name__ == "__main__":
    main()
